"""Component 2 — the single normalised fare-quote record schema.

Every collector (live scraper, synthetic generator) emits exactly this record.
Nothing downstream is allowed to see a source-specific shape.

Two design rules drive the schema, both taken straight from the brief:

  * Missing data is *recorded*, never dropped.  A sold-out flight, a failed
    fetch, and a robots.txt refusal are all first-class ``QuoteStatus`` values
    carrying a NULL fare — not absent rows.  Dropping sold-out quotes silently
    biases an airfare index downward, because sold-out is exactly what happens
    when a route is expensive.

  * Provenance is structural, not a comment.  ``collection_mode`` is a required
    field with no default, so synthetic data physically cannot enter the
    pipeline unlabelled.
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass, asdict, field
from datetime import date, datetime, timezone
from enum import Enum
from typing import Any, Optional

SCHEMA_VERSION = "1.1.0"


class CollectionMode(str, Enum):
    """How the quote physically came to exist. Never inferred, always set."""
    LIVE_SCRAPE = "LIVE_SCRAPE"   # a real HTTP response from a scraped page
    BROWSER_SCRAPE = "BROWSER_SCRAPE"  # a headless browser rendered the page first
    OFFICIAL_API = "OFFICIAL_API"  # a licensed API (Amadeus), not scraping
    SYNTHETIC = "SYNTHETIC"       # generated by pushpak.collect.synthetic


class SourceType(str, Enum):
    AIRLINE = "AIRLINE"
    OTA = "OTA"
    GDS = "GDS"                   # a global distribution system, via its API
    SYNTHETIC = "SYNTHETIC"


class QuoteStatus(str, Enum):
    """Why a fare is or isn't present. Fares are NULL for everything but OK."""
    OK = "OK"                          # a real, usable price
    SOLD_OUT = "SOLD_OUT"              # inventory exhausted at this fare class
    NO_SERVICE = "NO_SERVICE"          # no flight operates on this date/route
    CANCELLED = "CANCELLED"            # flight listed but cancelled
    FETCH_FAILED = "FETCH_FAILED"      # network/HTTP error
    PARSE_FAILED = "PARSE_FAILED"      # page fetched but fares not extractable
    BLOCKED_BY_ROBOTS = "BLOCKED_BY_ROBOTS"  # robots.txt disallowed the path
    CAPTCHA_BLOCKED = "CAPTCHA_BLOCKED"      # a human-verification wall was served
    BOT_BLOCKED = "BOT_BLOCKED"              # WAF/anti-bot rejected the client
    OUTLIER_REJECTED = "OUTLIER_REJECTED"    # price present but implausible


#: Statuses whose fare must be NULL. Enforced by ``FareQuote.validate``.
NULL_FARE_STATUSES = frozenset(
    {
        QuoteStatus.SOLD_OUT, QuoteStatus.NO_SERVICE, QuoteStatus.CANCELLED,
        QuoteStatus.FETCH_FAILED, QuoteStatus.PARSE_FAILED,
        QuoteStatus.BLOCKED_BY_ROBOTS, QuoteStatus.CAPTCHA_BLOCKED,
        QuoteStatus.BOT_BLOCKED,
    }
)

#: Statuses that count as an observed price for index purposes.
PRICED_STATUSES = frozenset({QuoteStatus.OK})


#: Cabins the schema will accept. Kept here rather than in config so that a
#: FareQuote can validate itself without importing the whole configuration.
ALLOWED_FARE_CLASSES = frozenset(
    {"ECONOMY", "PREMIUM_ECONOMY", "BUSINESS", "FIRST"}
)


class ImputationMethod(str, Enum):
    """Component 3 — CPI-standard imputation rules. See README §Imputation."""
    NONE = "NONE"
    CARRY_FORWARD = "CARRY_FORWARD"    # last observation carried forward (LOCF)
    CLASS_MEAN = "CLASS_MEAN"          # overall/class-mean imputation
    BASE_CARRY = "BASE_CARRY"          # hold at base period (relative = 1.0)


@dataclass
class FareQuote:
    """One fare observation for one (route, carrier, source, travel date)."""

    # --- identity -------------------------------------------------------
    origin: str                    # IATA, directional
    destination: str               # IATA, directional
    route_id: str                  # canonical undirected, e.g. "BOM-DEL"
    carrier: str                   # IATA airline code, or "" when unknown
    source: str                    # "goindigo.in", "cleartrip.com", "synthetic-v1"
    source_type: SourceType
    collection_mode: CollectionMode   # REQUIRED. No default. See module docstring.

    # --- timing ---------------------------------------------------------
    scrape_ts: str                 # ISO-8601 UTC, when the quote was captured
    observation_date: str          # YYYY-MM-DD, the index day this belongs to
    travel_date: str               # YYYY-MM-DD, the flight's departure date
    advance_purchase_days: int     # travel_date - observation_date

    # --- the price ------------------------------------------------------
    fare_class: str = "ECONOMY"
    base_fare: Optional[float] = None      # INR, excl. taxes & fees
    taxes_fees: Optional[float] = None     # INR, ALL statutory + platform charges
    total_fare: Optional[float] = None     # INR, what a passenger actually pays
    currency: str = "INR"

    # --- optional itemisation of taxes_fees ------------------------------
    # Schema v1.1.0. These exist so a licensed feed that DOES itemise can be
    # ingested without a migration; no public fare page publishes the split,
    # so in practice they stay NULL and ``taxes_fees`` carries the aggregate.
    # NULL here means "this source did not disclose it", never "it is zero" --
    # which is exactly the distinction the brief asks be made explicit.
    udf_fee: Optional[float] = None         # User Development Fee (airport)
    convenience_fee: Optional[float] = None  # OTA/booking-channel charge

    # --- data quality ---------------------------------------------------
    quote_status: QuoteStatus = QuoteStatus.OK
    is_imputed: bool = False
    imputation_method: ImputationMethod = ImputationMethod.NONE
    imputed_from: Optional[str] = None      # human-readable provenance of the fill

    # --- optional detail / audit ---------------------------------------
    flight_number: Optional[str] = None
    departure_time: Optional[str] = None    # HH:MM local
    stops: Optional[int] = None
    audit_request_id: Optional[str] = None  # -> scrape_audit.request_id
    notes: Optional[str] = None
    schema_version: str = SCHEMA_VERSION
    quote_id: str = field(default="", init=False)

    # ------------------------------------------------------------------
    def __post_init__(self) -> None:
        self.source_type = SourceType(self.source_type)
        self.collection_mode = CollectionMode(self.collection_mode)
        self.quote_status = QuoteStatus(self.quote_status)
        self.imputation_method = ImputationMethod(self.imputation_method)
        self.route_id = canonical_route_id(self.origin, self.destination) \
            if not self.route_id else self.route_id
        self.quote_id = self._make_id()

    def _make_id(self) -> str:
        key = "|".join(
            str(x) for x in (
                self.observation_date, self.route_id, self.origin, self.destination,
                self.carrier, self.source, self.travel_date,
                self.advance_purchase_days, self.fare_class,
                self.flight_number or "", self.departure_time or "",
                self.collection_mode.value,
            )
        )
        return hashlib.sha1(key.encode()).hexdigest()[:20]

    # ------------------------------------------------------------------
    def validate(self) -> list[str]:
        """Return a list of schema violations. Empty list == valid."""
        errs: list[str] = []

        if self.quote_status in NULL_FARE_STATUSES and self.total_fare is not None:
            errs.append(
                f"{self.quote_status.value} must carry a NULL total_fare, "
                f"got {self.total_fare}"
            )
        if self.quote_status == QuoteStatus.OK and self.total_fare is None:
            errs.append("status OK requires a non-null total_fare")
        if self.total_fare is not None and self.total_fare <= 0:
            errs.append(f"total_fare must be positive, got {self.total_fare}")
        if (
            self.base_fare is not None
            and self.taxes_fees is not None
            and self.total_fare is not None
            and abs((self.base_fare + self.taxes_fees) - self.total_fare) > 1.0
        ):
            errs.append(
                f"base_fare + taxes_fees ({self.base_fare + self.taxes_fees:.2f}) "
                f"!= total_fare ({self.total_fare:.2f})"
            )
        # Itemised components can never exceed the aggregate they decompose.
        itemised = [x for x in (self.udf_fee, self.convenience_fee) if x is not None]
        if itemised:
            if any(x < 0 for x in itemised):
                errs.append("itemised fees must be >= 0")
            if self.taxes_fees is not None and sum(itemised) - self.taxes_fees > 1.0:
                errs.append(
                    f"udf_fee + convenience_fee ({sum(itemised):.2f}) exceeds "
                    f"taxes_fees ({self.taxes_fees:.2f})"
                )
            if self.quote_status in NULL_FARE_STATUSES:
                errs.append(
                    f"{self.quote_status.value} must carry NULL fee itemisation"
                )
        if self.fare_class not in ALLOWED_FARE_CLASSES:
            errs.append(
                f"fare_class {self.fare_class!r} not in {sorted(ALLOWED_FARE_CLASSES)}"
            )
        if self.advance_purchase_days < 0:
            errs.append("advance_purchase_days must be >= 0")
        if self.is_imputed and self.imputation_method == ImputationMethod.NONE:
            errs.append("is_imputed=True requires an imputation_method")
        if not self.is_imputed and self.imputation_method != ImputationMethod.NONE:
            errs.append("imputation_method set but is_imputed=False")
        try:
            d_obs = date.fromisoformat(self.observation_date)
            d_trv = date.fromisoformat(self.travel_date)
            if (d_trv - d_obs).days != self.advance_purchase_days:
                errs.append(
                    f"advance_purchase_days ({self.advance_purchase_days}) "
                    f"!= travel_date - observation_date ({(d_trv - d_obs).days})"
                )
        except ValueError as exc:
            errs.append(f"bad date: {exc}")
        return errs

    def to_row(self) -> dict[str, Any]:
        d = asdict(self)
        d["quote_id"] = self.quote_id
        for k in ("source_type", "collection_mode", "quote_status", "imputation_method"):
            d[k] = d[k].value if hasattr(d[k], "value") else str(d[k])
        d["is_imputed"] = int(self.is_imputed)
        return d

    @property
    def cell_id(self) -> str:
        """Elementary-aggregate cell: (route, advance-purchase window)."""
        return f"{self.route_id}@T+{self.advance_purchase_days}"


# ---------------------------------------------------------------------------
def canonical_route_id(a: str, b: str) -> str:
    """Undirected route id. BOM->DEL and DEL->BOM both give 'BOM-DEL'."""
    return "-".join(sorted((a.upper().strip(), b.upper().strip())))


def utc_now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


